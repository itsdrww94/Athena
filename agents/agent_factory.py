def generate_agent_name(task: str) -> str:
    """Generate a snake_case agent name from task description."""
    # Extract key words
    words = re.findall(r'\b[a-zA-Z]+\b', task.lower())
    
    # Common action words
    actions = {"check", "get", "fetch", "scrape", "monitor", "track", "find", "search", "scan", "analyze"}
    
    # Find action and subject
    action = None
    subject = None
    
    for word in words:
        if word in actions and not action:
            action = word
        elif word not in {"the", "a", "an", "to", "for", "from", "of", "my", "and", "or"} and not subject:
            if action:  # Only set subject after finding action
                subject = word
    
    if action and subject:
        return f"{action}_{subject}"
    elif subject:
        return f"check_{subject}"
    else:
        return f"agent_{datetime.now().strftime('%H%M%S')}"


def create_agent(task: str, name: Optional[str] = None, auto_run: bool = False, run_args: str = "") -> dict:
    """
    Generate a new agent using Claude.
    
    Args:
        task: Description of what the agent should do
        name: Optional custom name for the agent
        auto_run: Whether to run the agent after creation
        run_args: Arguments to pass if auto-running
        
    Returns:
        Result dict with success status, path, and any output
    """
    print(f"🏭 Agent Factory: Building new agent...")
    print(f"📋 Task: {task}")
    
    # Generate name if not provided
    agent_name = name or generate_agent_name(task)
    agent_name = re.sub(r'[^a-z0-9_]', '', agent_name.lower())
    
    if not agent_name.endswith('.py'):
        agent_name += '.py'
    
    agent_path = AGENTS_DIR / agent_name
    
    print(f"📝 Agent name: {agent_name}")
    
    # Call Claude to generate code
    print("🤖 Calling Claude 3.5 Sonnet...")
    raw_code = call_claude(task)
    
    if not raw_code:
        return {"success": False, "error": "Claude API call failed"}
    
    # Extract and clean code
    code = extract_code(raw_code)
    
    # Validate syntax
    is_valid, error = validate_syntax(code)
    if not is_valid:
        print(f"⚠️ Syntax validation failed: {error}")
        print("🔧 Attempting to fix...")
        # Could add retry logic here
        return {"success": False, "error": f"Generated code has syntax errors: {error}"}
    
    # Validate structure
    is_valid, error = validate_structure(code)
    if not is_valid:
        print(f"⚠️ Structure validation: {error}")
        # Non-fatal, continue anyway
    
    # Write to file
    try:
        with open(agent_path, 'w', encoding='utf-8') as f:
            f.write(code)
        print(f"✅ Agent created: {agent_path}")
    except Exception as e:
        return {"success": False, "error": f"Failed to write file: {e}"}
    
    result = {
        "success": True,
        "path": str(agent_path),
        "name": agent_name,
        "code_lines": len(code.split('\n'))
    }
    
    # Auto-run if requested
    if auto_run:
        print(f"🚀 Auto-running agent...")
        try:
            cmd = [sys.executable, str(agent_path)]
            if run_args:
                cmd.extend(run_args.split())
            
            run_result = subprocess.run(
                cmd,
                capture_output=True,
                text=True,
                timeout=30,
                cwd=str(BASE_DIR)
            )
            
            result["output"] = run_result.stdout or run_result.stderr
            result["return_code"] = run_result.returncode
            
            if run_result.returncode == 0:
                print(f"✅ Agent executed successfully!")
            else:
                print(f"⚠️ Agent returned code {run_result.returncode}")
            
            if run_result.stdout:
                print("\n--- Agent Output ---")
                print(run_result.stdout)
            
        except subprocess.TimeoutExpired:
            result["output"] = "Execution timed out (30s)"
            print("⏰ Agent execution timed out")
        except Exception as e:
            result["output"] = f"Execution error: {e}"
            print(f"❌ Execution error: {e}")
    
    return result


