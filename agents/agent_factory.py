def extract_code(raw_response: str) -> str:
    """
    Extract clean Python code from Claude's response.
    Handles cases where Claude might include markdown despite instructions.
    """
    code = raw_response.strip()
    
    # Remove markdown code blocks if present
    if "```python" in code:
        match = re.search(r'```python\n(.*?)```', code, re.DOTALL)
        if match:
            code = match.group(1)
    elif "```" in code:
        match = re.search(r'```\n?(.*?)```', code, re.DOTALL)
        if match:
            code = match.group(1)
    
    return code.strip()


def validate_syntax(code: str) -> Tuple[bool, str]:
    """
    Validate Python syntax using ast.parse().
    
    Returns:
        Tuple of (is_valid, error_message)
    """
    try:
        ast.parse(code)
        return True, ""
    except SyntaxError as e:
        return False, f"Syntax error at line {e.lineno}: {e.msg}"


def validate_structure(code: str) -> Tuple[bool, str]:
    """
    Validate that code has required structure (main function, argparse).
    """
    if "def main(" not in code:
        return False, "Missing main() function"
    
    if "argparse" not in code and "ArgumentParser" not in code:
        return False, "Missing argparse usage"
    
    return True, ""


