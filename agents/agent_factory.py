def call_claude(task_description: str) -> Optional[str]:
    """
    Call Claude 3.5 Sonnet to generate agent code.
    
    Args:
        task_description: What the agent should do
        
    Returns:
        Generated Python code or None on error
    """
    if not ANTHROPIC_API_KEY:
        print("❌ ANTHROPIC_API_KEY not set in .env")
        return None
    
    try:
        import httpx
        
        response = httpx.post(
            "https://api.anthropic.com/v1/messages",
            headers={
                "x-api-key": ANTHROPIC_API_KEY,
                "anthropic-version": "2023-06-01",
                "content-type": "application/json"
            },
            json={
                "model": "claude-sonnet-4-20250514",
                "max_tokens": 4096,
                "system": CLAUDE_SYSTEM_PROMPT,
                "messages": [
                    {
                        "role": "user",
                        "content": f"Create a Python script that does the following:\n\n{task_description}\n\nRemember: Return ONLY executable Python code, no markdown."
                    }
                ]
            },
            timeout=60.0
        )
        
        response.raise_for_status()
        data = response.json()
        
        # Extract text from response
        content = data.get("content", [])
        if content and len(content) > 0:
            return content[0].get("text", "")
        
        return None
        
    except ImportError:
        print("❌ httpx not installed. Run: pip install httpx")
        return None
    except Exception as e:
        print(f"❌ Claude API error: {e}")
        return None


