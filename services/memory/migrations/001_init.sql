-- ============================================================================
-- ATHENA CANONICAL SCHEMA v2.0
-- ============================================================================
-- This is THE canonical schema for Athena's memory system.
-- All other schema files should be considered legacy.
-- 
-- Tables:
--   1. memory_events    - Append-only conversation/action log
--   2. memory_facts     - Durable facts about the user
--   3. memory_chunks    - Embeddings for semantic search
--   4. agent_runs       - Observability/telemetry records
--   5. user_facts       - (Legacy alias, kept for compatibility)
-- ============================================================================

-- Enable required extensions
CREATE EXTENSION IF NOT EXISTS "pgcrypto";
CREATE EXTENSION IF NOT EXISTS "vector";

-- ============================================================================
-- 1. MEMORY_EVENTS (Append-only conversation log)
-- ============================================================================
-- Every user message, assistant response, and tool call is logged here.
-- This is the source of truth for conversation history.

CREATE TABLE IF NOT EXISTS memory_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL DEFAULT 'default',
    session_id TEXT NOT NULL DEFAULT 'default',
    role TEXT NOT NULL CHECK (role IN ('user', 'assistant', 'system', 'tool')),
    content TEXT NOT NULL,
    metadata_json JSONB DEFAULT '{}'::JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_memory_events_user_session 
    ON memory_events(user_id, session_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_memory_events_created 
    ON memory_events(created_at DESC);

ALTER TABLE memory_events ENABLE ROW LEVEL SECURITY;
DO $$ 
BEGIN
    DROP POLICY IF EXISTS "Full access to memory_events" ON memory_events;
    CREATE POLICY "Full access to memory_events" ON memory_events 
        FOR ALL USING (true) WITH CHECK (true);
END $$;

-- ============================================================================
-- 2. MEMORY_FACTS (Durable user facts)
-- ============================================================================
-- Long-lived facts about the user: preferences, profile info, goals.
-- Updated via upsert, not append-only.

CREATE TABLE IF NOT EXISTS memory_facts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL DEFAULT 'default',
    key TEXT NOT NULL,
    value_json JSONB NOT NULL,
    category TEXT DEFAULT 'preference',  -- preference, personal, goal, system
    confidence REAL DEFAULT 1.0 CHECK (confidence >= 0 AND confidence <= 1),
    source TEXT DEFAULT 'inference',     -- inference, explicit, system
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
    UNIQUE(user_id, key)
);

CREATE INDEX IF NOT EXISTS idx_memory_facts_user ON memory_facts(user_id);
CREATE INDEX IF NOT EXISTS idx_memory_facts_category ON memory_facts(category);

-- Auto-update timestamp trigger
CREATE OR REPLACE FUNCTION update_memory_facts_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_memory_facts_modtime ON memory_facts;
CREATE TRIGGER update_memory_facts_modtime
    BEFORE UPDATE ON memory_facts
    FOR EACH ROW
    EXECUTE FUNCTION update_memory_facts_timestamp();

ALTER TABLE memory_facts ENABLE ROW LEVEL SECURITY;
DO $$ 
BEGIN
    DROP POLICY IF EXISTS "Full access to memory_facts" ON memory_facts;
    CREATE POLICY "Full access to memory_facts" ON memory_facts 
        FOR ALL USING (true) WITH CHECK (true);
END $$;

-- ============================================================================
-- 3. MEMORY_CHUNKS (Semantic search embeddings)
-- ============================================================================
-- Chunked documents with vector embeddings for RAG.
-- Uses pgvector for similarity search.

CREATE TABLE IF NOT EXISTS memory_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL DEFAULT 'default',
    source TEXT NOT NULL,           -- 'conversation', 'document', 'note'
    chunk_text TEXT NOT NULL,
    embedding VECTOR(768),          -- Adjust dimension based on model
    metadata_json JSONB DEFAULT '{}'::JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- HNSW index for fast similarity search
CREATE INDEX IF NOT EXISTS idx_memory_chunks_embedding 
    ON memory_chunks USING hnsw (embedding vector_cosine_ops);
CREATE INDEX IF NOT EXISTS idx_memory_chunks_user 
    ON memory_chunks(user_id);
CREATE INDEX IF NOT EXISTS idx_memory_chunks_source 
    ON memory_chunks(source);

ALTER TABLE memory_chunks ENABLE ROW LEVEL SECURITY;
DO $$ 
BEGIN
    DROP POLICY IF EXISTS "Full access to memory_chunks" ON memory_chunks;
    CREATE POLICY "Full access to memory_chunks" ON memory_chunks 
        FOR ALL USING (true) WITH CHECK (true);
END $$;

-- Function for similarity search
CREATE OR REPLACE FUNCTION match_memory_chunks(
    query_embedding VECTOR(768),
    match_threshold FLOAT DEFAULT 0.7,
    match_count INT DEFAULT 8,
    filter_user_id TEXT DEFAULT NULL
)
RETURNS TABLE (
    id BIGINT,
    user_id TEXT,
    source TEXT,
    chunk_text TEXT,
    metadata_json JSONB,
    similarity FLOAT
)
LANGUAGE plpgsql
AS $$
BEGIN
    RETURN QUERY
    SELECT
        mc.id,
        mc.user_id,
        mc.source,
        mc.chunk_text,
        mc.metadata_json,
        1 - (mc.embedding <=> query_embedding) AS similarity
    FROM memory_chunks mc
    WHERE 
        (filter_user_id IS NULL OR mc.user_id = filter_user_id)
        AND 1 - (mc.embedding <=> query_embedding) > match_threshold
    ORDER BY mc.embedding <=> query_embedding
    LIMIT match_count;
END;
$$;

