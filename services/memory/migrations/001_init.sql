-- ============================================================================
-- 5. USER_FACTS (Legacy compatibility alias)
-- ============================================================================
-- This view provides backward compatibility with existing code that uses
-- the user_facts table directly. Maps to memory_facts.
-- ============================================================================
-- 5. USER_FACTS (Legacy compatibility alias)
-- ============================================================================
-- This handled the "user_facts is not a view" error by checking if a legacy
-- user_facts TABLE exists, backing it up, migrating data, and then replacing
-- it with a View.

DO $$ 
BEGIN
    -- Check if user_facts exists AND is a table (not a view)
    IF EXISTS (
        SELECT FROM pg_tables 
        WHERE schemaname = 'public' AND tablename = 'user_facts'
    ) THEN
        RAISE NOTICE 'Legacy user_facts table detected. Renaming and migrating data...';
        
        -- 1. Rename the legacy table
        ALTER TABLE user_facts RENAME TO user_facts_legacy_backup;
        
        -- 2. Migrate data to the new memory_facts table
        --    Map 'value' (legacy) to 'value_json' (new)
        INSERT INTO memory_facts (user_id, key, value_json, category, confidence, source, created_at, updated_at)
        SELECT 
            'default', 
            key, 
            value, 
            category, 
            confidence, 
            source, 
            created_at, 
            updated_at
        FROM user_facts_legacy_backup
        ON CONFLICT (user_id, key) DO NOTHING;
        
        RAISE NOTICE 'Data migration complete. user_facts is now user_facts_legacy_backup.';
    END IF;
END $$;

-- Now safe to create the view
CREATE OR REPLACE VIEW user_facts AS
SELECT 
    id,
    key,
    value_json AS value,
    category,
    confidence,
    source,
    created_at,
    updated_at
FROM memory_facts
WHERE user_id = 'default';

