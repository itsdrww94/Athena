-- 2. AGENT_STATES (Key-Value Store for Agents)
CREATE TABLE IF NOT EXISTS agent_states (
    agent_name TEXT NOT NULL,
    key TEXT NOT NULL,
    value JSONB DEFAULT '{}'::JSONB,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL,
    PRIMARY KEY (agent_name, key)
);

CREATE OR REPLACE FUNCTION update_agent_states_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS update_agent_states_modtime ON agent_states;
CREATE TRIGGER update_agent_states_modtime
    BEFORE UPDATE ON agent_states
    FOR EACH ROW
    EXECUTE FUNCTION update_agent_states_timestamp();

