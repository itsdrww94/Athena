-- 1. MEMORY_LOGS (Episodic Memory / Chat History)
CREATE TABLE IF NOT EXISTS memory_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT,
    user_input TEXT NOT NULL,
    athena_response TEXT NOT NULL,
    summary TEXT,
    intent TEXT,
    sentiment TEXT,
    tokens_used INTEGER DEFAULT 0,
    source TEXT DEFAULT 'telegram',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::TEXT, NOW()) NOT NULL
);

-- MIGRATION: Ensure columns exist if table was already there
DO $$ 
BEGIN 
    BEGIN
        ALTER TABLE memory_logs ADD COLUMN session_id TEXT;
    EXCEPTION
        WHEN duplicate_column THEN NULL;
    END;
    BEGIN
        ALTER TABLE memory_logs ADD COLUMN source TEXT DEFAULT 'telegram';
    EXCEPTION
        WHEN duplicate_column THEN NULL;
    END;
END $$;

CREATE INDEX IF NOT EXISTS idx_memory_logs_created ON memory_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_memory_logs_session ON memory_logs(session_id);

