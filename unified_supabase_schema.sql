-- MIGRATION: Ensure unique key for ON CONFLICT support
DO $$ 
BEGIN 
    -- 1. Deduplicate keys (keeping latest)
    DELETE FROM user_facts 
    WHERE id IN (
        SELECT id FROM (
            SELECT id, ROW_NUMBER() OVER (partition BY key ORDER BY id DESC) AS rnum 
            FROM user_facts
        ) t 
        WHERE t.rnum > 1
    );
    
    -- 2. Create unique index (required for ON CONFLICT (key))
    CREATE UNIQUE INDEX IF NOT EXISTS idx_user_facts_unique_key ON user_facts(key);
END $$;

